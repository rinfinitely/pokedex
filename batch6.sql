-- #49 Lightweight activity events for follower feed (optional; feed also works from card updated_at)
create table if not exists public.activity_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null default '',
  kind text not null default 'update' check (char_length(kind) <= 40),
  title text not null default '' check (char_length(title) <= 120),
  body text not null default '' check (char_length(body) <= 300),
  url text not null default '' check (char_length(url) <= 300),
  created_at timestamptz not null default now()
);
create index if not exists activity_events_user_time on public.activity_events (user_id, created_at desc);
create index if not exists activity_events_time on public.activity_events (created_at desc);
alter table public.activity_events enable row level security;
drop policy if exists activity_read on public.activity_events;
create policy activity_read on public.activity_events for select to authenticated using (true);
drop policy if exists activity_insert on public.activity_events;
create policy activity_insert on public.activity_events for insert to authenticated
  with check (user_id = auth.uid());
drop policy if exists activity_delete on public.activity_events;
create policy activity_delete on public.activity_events for delete to authenticated
  using (user_id = auth.uid() or public.is_admin());
