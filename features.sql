create table if not exists public.badges (
  id          bigint generated by default as identity primary key,
  slug        text unique not null check (slug ~ '^[a-z0-9_-]{2,40}$'),
  name        text not null check (char_length(name) between 1 and 60),
  description text not null default '' check (char_length(description) <= 300),
  kind        text not null default 'milestone' check (kind in ('milestone', 'custom')),
  metric      text check (metric in ('caught', 'pct', 'shiny', 'special', 'trade_items', 'friend_code')),
  threshold   numeric,
  image_url   text not null default '' check (char_length(image_url) <= 120000),   -- https link, or a small data: image made in the badge editor
  emoji       text not null default '🏅' check (char_length(emoji) <= 8),
  color       text not null default '#f4c96b' check (color ~ '^#[0-9a-fA-F]{6}$'),
  secret      boolean not null default false,   -- secret badges are hidden until someone earns them
  sort        int not null default 100,
  created_at  timestamptz not null default now(),
  check (kind = 'custom' or (metric is not null and threshold is not null))
);
