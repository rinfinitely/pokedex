  auth_key   text not null,
  tz         text not null default 'UTC',
  prefs      jsonb not null default '{"events":true,"matches":true,"announce":true}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
drop policy if exists push_subs_own on public.push_subscriptions;
create policy push_subs_own on public.push_subscriptions for all to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
-- re-assigns a browser's subscription to whoever is logged in on it now (a plain upsert would be blocked by the row's old owner)
create or replace function public.save_push_subscription(p_endpoint text, p_p256dh text, p_auth text, p_tz text, p_prefs jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'Log in first'; end if;
  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth_key, tz, prefs)
  values (auth.uid(), p_endpoint, p_p256dh, p_auth, coalesce(nullif(p_tz, ''), 'UTC'), coalesce(p_prefs, '{}'::jsonb))
  on conflict (endpoint) do update set user_id = auth.uid(), p256dh = excluded.p256dh, auth_key = excluded.auth_key, tz = excluded.tz, prefs = excluded.prefs;
end $$;
grant execute on function public.save_push_subscription(text, text, text, text, jsonb) to authenticated;

