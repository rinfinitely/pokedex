-- if an admin edits the date of an imported event, it becomes a normal fixed-time event
create or replace function public.events_unfloat() returns trigger language plpgsql as $$
begin
  if new.floating and (new.starts_at is distinct from old.starts_at or new.ends_at is distinct from old.ends_at) then new.floating := false; end if;
  return new;
end $$;
drop trigger if exists events_unfloat on public.events;
create trigger events_unfloat before update on public.events for each row execute function public.events_unfloat();

