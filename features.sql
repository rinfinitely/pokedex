-- one guard on every new chat message: mutes, blocked words, slow mode (admins are exempt)
create or replace function public.messages_guard() returns trigger language plpgsql security definer set search_path = public as $$
declare w text; secs int; uid uuid := coalesce(new.user_id, auth.uid());
begin
  if public.is_admin() then return new; end if;
  if exists (select 1 from public.mutes m where m.user_id = uid and m.until_at > now()) then
    raise exception 'You are muted and cannot post right now.';
  end if;
  for w in select word from public.banned_words loop
    if coalesce(new.body, '') ~* ('\m' || regexp_replace(w, '([.^$*+?()\[\]{}|\\])', '\\\1', 'g') || '\M') then
      raise exception 'That message contains a blocked word.';
    end if;
  end loop;
  select nullif(value->>'seconds', '')::int into secs from public.site_settings where key = 'slowmode';
  if coalesce(secs, 0) > 0 and exists (select 1 from public.messages m where m.user_id = uid and m.created_at > now() - make_interval(secs => secs)) then
    raise exception 'Slow mode is on: wait % seconds between messages.', secs;
  end if;
  return new;
end $$;
drop trigger if exists messages_guard on public.messages;
create trigger messages_guard before insert on public.messages for each row execute function public.messages_guard();

-- ---------- 6. ADMIN ANALYTICS (one call, admins only) ----------
create or replace function public.admin_analytics() returns jsonb language plpgsql security definer set search_path = public, auth as $$
declare r jsonb;
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  select jsonb_build_object(
    'users',   (select count(*) from auth.users),
    'new7',    (select count(*) from auth.users where created_at > now() - interval '7 days'),
    'new30',   (select count(*) from auth.users where created_at > now() - interval '30 days'),
    'signups', (select coalesce(jsonb_agg(jsonb_build_object('d', d, 'n', n) order by d), '[]'::jsonb) from (select created_at::date d, count(*) n from auth.users where created_at > now() - interval '30 days' group by 1) s),
    'active24',(select count(*) from public.cloud_dex where updated_at > now() - interval '24 hours'),
    'active7', (select count(*) from public.cloud_dex where updated_at > now() - interval '7 days'),
    'messages',(select coalesce(jsonb_agg(jsonb_build_object('d', d, 'n', n) order by d), '[]'::jsonb) from (select created_at::date d, count(*) n from public.messages where created_at > now() - interval '14 days' group by 1) m),
    'chatters7',(select count(distinct user_id) from public.messages where created_at > now() - interval '7 days'),
    'public',  (select count(*) from public.trainer_cards where is_public),
    'sharing', (select count(*) from public.trainer_cards where show_trade),
    'teams',   (select coalesce(jsonb_object_agg(t, n), '{}'::jsonb) from (select coalesce(nullif(team, ''), 'none') t, count(*) n from public.trainer_cards group by 1) x),
    'avg_pct', (select coalesce(round(avg(pct)::numeric, 1), 0) from public.trainer_cards),
    'shiny_total', (select coalesce(sum(shiny), 0) from public.trainer_cards),
    'top_want', (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'n', n) order by n desc), '[]'::jsonb) from (
        select (x->>'id')::int id, count(*) n from public.trainer_cards t,
          jsonb_array_elements(case when jsonb_typeof(t.trade->'want') = 'array' then t.trade->'want' else '[]'::jsonb end) x
        where t.show_trade and (x->>'id') ~ '^[0-9]{1,4}$' group by 1 order by n desc limit 15) q),
    'top_offer', (select coalesce(jsonb_agg(jsonb_build_object('id', id, 'n', n) order by n desc), '[]'::jsonb) from (
        select (x->>'id')::int id, count(*) n from public.trainer_cards t,
          jsonb_array_elements(case when jsonb_typeof(t.trade->'offer') = 'array' then t.trade->'offer' else '[]'::jsonb end) x
        where t.show_trade and (x->>'id') ~ '^[0-9]{1,4}$' group by 1 order by n desc limit 15) q),
    'badges',  (select coalesce(jsonb_agg(jsonb_build_object('name', b.name, 'n', c.n) order by c.n desc), '[]'::jsonb)
                from (select badge_id, count(*) n from public.user_badges group by 1 order by n desc limit 10) c join public.badges b on b.id = c.badge_id),
    'push_subs', (select count(*) from public.push_subscriptions),
    'open_reports', (select count(*) from public.reports) + (select count(*) from public.content_reports where status = 'open'),
    'muted',   (select count(*) from public.mutes where until_at > now()),
    'events_upcoming', (select count(*) from public.events where starts_at > now())
  ) into r;
  return r;
end $$;
grant execute on function public.admin_analytics() to authenticated;

