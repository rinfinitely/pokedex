-- #58 Profile views counter
alter table public.trainer_cards
  add column if not exists profile_views bigint not null default 0;

create or replace function public.bump_profile_views(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.trainer_cards
     set profile_views = profile_views + 1
   where user_id = p_user_id and is_public = true;
end;
$$;
grant execute on function public.bump_profile_views(uuid) to anon, authenticated;

-- #59 Custom profile URL slug
alter table public.trainer_cards
  add column if not exists profile_slug text not null default ''
  check (char_length(profile_slug) <= 40);

create unique index if not exists trainer_cards_slug_uidx
  on public.trainer_cards (lower(profile_slug))
  where profile_slug <> '';

-- #134 Role tiers: moderator (limited) vs admin
alter table public.profiles
  add column if not exists is_mod boolean not null default false;

create or replace function public.is_mod()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select p.is_mod or p.is_admin from public.profiles p where p.id = auth.uid()),
    false
  );
$$;
grant execute on function public.is_mod() to authenticated;

-- #127 Ban appeals
create table if not exists public.ban_appeals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null default '',
  reason text not null check (char_length(reason) between 10 and 1000),
  status text not null default 'open' check (status in ('open', 'accepted', 'rejected')),
  admin_note text not null default '',
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid
);
create index if not exists ban_appeals_status_idx on public.ban_appeals (status, created_at desc);
create index if not exists ban_appeals_user_idx on public.ban_appeals (user_id, created_at desc);
alter table public.ban_appeals enable row level security;
drop policy if exists ban_appeals_insert on public.ban_appeals;
create policy ban_appeals_insert on public.ban_appeals for insert to authenticated
  with check (user_id = auth.uid());
drop policy if exists ban_appeals_read on public.ban_appeals;
create policy ban_appeals_read on public.ban_appeals for select to authenticated
  using (user_id = auth.uid() or public.is_admin());
drop policy if exists ban_appeals_admin on public.ban_appeals;
create policy ban_appeals_admin on public.ban_appeals for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- Allow ban appeals without an active session (banned users are signed out)
create or replace function public.submit_ban_appeal(p_username text, p_reason text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid;
  uname text := lower(trim(p_username));
begin
  if char_length(trim(p_reason)) < 10 or char_length(trim(p_reason)) > 1000 then
    raise exception 'Reason must be 10–1000 characters';
  end if;
  if char_length(uname) < 2 then
    raise exception 'Username required';
  end if;
  select id into uid from public.profiles where lower(username) = uname limit 1;
  if uid is null then
    raise exception 'No account found with that username';
  end if;
  if not exists (select 1 from public.profiles where id = uid and banned = true) then
    raise exception 'That account is not banned';
  end if;
  if exists (select 1 from public.ban_appeals where user_id = uid and status = 'open' and created_at > now() - interval '7 days') then
    raise exception 'You already have an open appeal from the last 7 days';
  end if;
  insert into public.ban_appeals (user_id, username, reason)
  values (uid, uname, trim(p_reason));
  return 'ok';
end;
$$;
grant execute on function public.submit_ban_appeal(text, text) to anon, authenticated;
