-- Profile avatars/banners + direct messages
-- Run in Supabase SQL Editor (safe to re-run)

alter table public.trainer_cards
  add column if not exists avatar_url text not null default '' check (char_length(avatar_url) <= 200000),
  add column if not exists banner_url text not null default '' check (char_length(banner_url) <= 200000);

-- Direct messages (1:1)
create table if not exists public.dm_messages (
  id bigint generated by default as identity primary key,
  from_id uuid not null references auth.users(id) on delete cascade,
  to_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now(),
  check (from_id <> to_id)
);
create index if not exists dm_messages_pair on public.dm_messages (from_id, to_id, id desc);
create index if not exists dm_messages_to on public.dm_messages (to_id, id desc);
alter table public.dm_messages enable row level security;
drop policy if exists dm_read on public.dm_messages;
create policy dm_read on public.dm_messages for select to authenticated
  using (from_id = auth.uid() or to_id = auth.uid());
drop policy if exists dm_insert on public.dm_messages;
create policy dm_insert on public.dm_messages for insert to authenticated
  with check (from_id = auth.uid());
drop policy if exists dm_delete on public.dm_messages;
create policy dm_delete on public.dm_messages for delete to authenticated
  using (from_id = auth.uid() or public.is_admin());
